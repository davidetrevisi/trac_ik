namespace
{

constexpr double kEps = 1e-5;       // solver convergence threshold
constexpr double kPosTol = 1e-3;    // metres, FK round-trip
constexpr double kRotTol = 1e-3;    // radians, FK round-trip
constexpr int kSamples = 200;
constexpr double kSolveRateFloor = 0.90;  // generous: tighten once ticket 10 seeds the RNG

std::string readFixture(const std::string& name)
{
  std::ifstream in(std::string(TRAC_IK_TEST_FIXTURE_DIR) + "/" + name);
  EXPECT_TRUE(in.good()) << "fixture not found: " << name;
  std::stringstream ss;
  ss << in.rdbuf();
  return ss.str();
}

// The chain, its limits, and an FK solver: everything a library-seam test needs.
struct Fixture
{
  urdf::Model model;
  KDL::Chain chain;
  KDL::JntArray lb, ub;
  std::vector<std::string> joint_names;

  Fixture(const std::string& urdf_file, const std::string& base, const std::string& tip)
  {
    const std::string xml = readFixture(urdf_file);
    EXPECT_TRUE(model.initString(xml));
    KDL::Tree tree;
    EXPECT_TRUE(kdl_parser::treeFromString(xml, tree));
    EXPECT_TRUE(tree.getChain(base, tip, chain));

    lb.resize(chain.getNrOfJoints());
    ub.resize(chain.getNrOfJoints());
    unsigned int i = 0;
    for (const auto& seg : chain.segments)
    {
      auto joint = model.getJoint(seg.getJoint().getName());
      if (!joint || joint->type == urdf::Joint::UNKNOWN || joint->type == urdf::Joint::FIXED)
        continue;
      joint_names.push_back(joint->name);
      // Mirrors trac_ik.cpp: a continuous joint is reported as unbounded via float sentinels.
      if (joint->type == urdf::Joint::CONTINUOUS)
      {
        lb(i) = std::numeric_limits<float>::lowest();
        ub(i) = std::numeric_limits<float>::max();
      }
      else
      {
        lb(i) = joint->limits->lower;
        ub(i) = joint->limits->upper;
      }
      ++i;
    }
    EXPECT_EQ(i, chain.getNrOfJoints());
  }

  bool unbounded(unsigned int i) const
  {
    return ub(i) >= std::numeric_limits<float>::max() && lb(i) <= std::numeric_limits<float>::lowest();
  }

  KDL::Frame fk(const KDL::JntArray& q) const
  {
    KDL::ChainFkSolverPos_recursive solver(chain);
    KDL::Frame f;
    EXPECT_GE(solver.JntToCart(q, f), 0);
    return f;
  }

  // A random full configuration inside the limits; continuous joints sample [-pi, pi].
  KDL::JntArray randomConfig(std::mt19937& rng) const
  {
    KDL::JntArray q(chain.getNrOfJoints());
    for (unsigned int i = 0; i < chain.getNrOfJoints(); ++i)
    {
      const double lo = unbounded(i) ? -M_PI : lb(i);
      const double hi = unbounded(i) ? M_PI : ub(i);
      q(i) = std::uniform_real_distribution<double>(lo, hi)(rng);
    }
    return q;
  }
};

void expectWithinLimits(const Fixture& f, const KDL::JntArray& q)
{
  for (unsigned int i = 0; i < q.rows(); ++i)
  {
    if (f.unbounded(i))
      continue;
    EXPECT_GE(q(i), f.lb(i) - 1e-6) << "joint " << f.joint_names[i] << " below its lower limit";
    EXPECT_LE(q(i), f.ub(i) + 1e-6) << "joint " << f.joint_names[i] << " above its upper limit";
  }
}

double positionError(const KDL::Frame& a, const KDL::Frame& b)
{
  return (a.p - b.p).Norm();
}

double rotationError(const KDL::Frame& a, const KDL::Frame& b)
{
  return (a.M.Inverse() * b.M).GetRot().Norm();
}

}  // namespace

// ---------------------------------------------------------------------------------------------
// arm6: a conventional 6-DOF arm, no mimic joints. Keeps the suite honest about the regressions
// the crane (5 active DOF, position-only) cannot show.
// ---------------------------------------------------------------------------------------------

TEST(TracIkLib, Arm6FullPoseRoundTrip)
{
  Fixture f("arm6.urdf", "base_link", "tool_link");
  TRAC_IK::TRAC_IK ik(f.chain, f.lb, f.ub, 0.05, kEps, TRAC_IK::Speed);

  std::mt19937 rng(1);  // test-side determinism: the TARGETS repeat, the solver's search does not
  int solved = 0;
  for (int n = 0; n < kSamples; ++n)
  {
    const KDL::Frame target = f.fk(f.randomConfig(rng));
    KDL::JntArray seed = f.randomConfig(rng), sol;
    if (ik.CartToJnt(seed, target, sol) < 0)
      continue;
    ++solved;
    expectWithinLimits(f, sol);
    const KDL::Frame reached = f.fk(sol);
    EXPECT_LT(positionError(target, reached), kPosTol);
    EXPECT_LT(rotationError(target, reached), kRotTol);
  }
  EXPECT_GE(static_cast<double>(solved) / kSamples, kSolveRateFloor)
      << "solved " << solved << " of " << kSamples;
}

TEST(TracIkLib, Arm6PositionOnlyToleranceFreesOrientation)
{
  Fixture f("arm6.urdf", "base_link", "tool_link");
  TRAC_IK::TRAC_IK ik(f.chain, f.lb, f.ub, 0.05, kEps, TRAC_IK::Speed);

  // Infinite rotational tolerance bounds: the three orientation components are free.
  KDL::Twist bounds = KDL::Twist::Zero();
  bounds.rot.x(std::numeric_limits<float>::max());
  bounds.rot.y(std::numeric_limits<float>::max());
  bounds.rot.z(std::numeric_limits<float>::max());

  std::mt19937 rng(2);
  int solved = 0;
  for (int n = 0; n < kSamples; ++n)
  {
    const KDL::Frame target = f.fk(f.randomConfig(rng));
    KDL::JntArray seed = f.randomConfig(rng), sol;
    if (ik.CartToJnt(seed, target, sol, bounds) < 0)
      continue;
    ++solved;
    expectWithinLimits(f, sol);
    // Position must still be met; orientation is explicitly not asserted.
    EXPECT_LT(positionError(target, f.fk(sol)), kPosTol);
  }
  EXPECT_GE(static_cast<double>(solved) / kSamples, kSolveRateFloor)
      << "solved " << solved << " of " << kSamples;
}

TEST(TracIkLib, Arm6ContinuousJointsAreUnbounded)
{
  Fixture f("arm6.urdf", "base_link", "tool_link");
  KDL::JntArray lb, ub;
  TRAC_IK::TRAC_IK ik(f.chain, f.lb, f.ub, 0.05, kEps, TRAC_IK::Speed);
  ASSERT_TRUE(ik.getKDLLimits(lb, ub));
  for (unsigned int i = 0; i < f.joint_names.size(); ++i)
  {
    const bool is_continuous = f.model.getJoint(f.joint_names[i])->type == urdf::Joint::CONTINUOUS;
    EXPECT_EQ(is_continuous, f.unbounded(i)) << "joint " << f.joint_names[i];
  }
}

// ---------------------------------------------------------------------------------------------
// The crane: 9 chain joints, 4 of them mimic joints, 5 active. Today the library has no notion of
// a mimic joint, so it treats all 9 as active. The coupling test below is the RED one ticket 04
// turns green.
// ---------------------------------------------------------------------------------------------

TEST(TracIkLib, CraneChainShape)
{
  Fixture f("crane.urdf", "base_link", "jib_ext_link");
  EXPECT_EQ(f.chain.getNrOfJoints(), 9u) << "the crane chain has 9 joints with variables";
  int mimics = 0;
  for (const auto& name : f.joint_names)
    if (f.model.getJoint(name)->mimic)
      ++mimics;
  EXPECT_EQ(mimics, 4) << "4 of them are mimic joints";
}

TEST(TracIkLib, CraneSolutionRespectsMimicCoupling)
{
  Fixture f("crane.urdf", "base_link", "jib_ext_link");
  // Distance, not Speed, and deliberately so: in Speed mode the KDL branch answers in ~1 ms with a
  // solution whose four parallel prismatic joints happen to be equal, so the coupling looks intact
  // and this test goes green for a reason that has nothing to do with mimic support. Distance
  // collects solutions for the whole timeout and the winner violates the coupling outright.
  TRAC_IK::TRAC_IK ik(f.chain, f.lb, f.ub, 0.05, kEps, TRAC_IK::Distance);

  // A mimic-consistent full configuration, so the target is reachable under the coupling.
  KDL::JntArray q(f.chain.getNrOfJoints());
  std::mt19937 rng(3);
  for (unsigned int i = 0; i < f.joint_names.size(); ++i)
  {
    const auto joint = f.model.getJoint(f.joint_names[i]);
    if (joint->mimic)
      continue;
    const double lo = f.unbounded(i) ? -M_PI : f.lb(i);
    const double hi = f.unbounded(i) ? M_PI : f.ub(i);
    q(i) = std::uniform_real_distribution<double>(lo, hi)(rng);
  }
  for (unsigned int i = 0; i < f.joint_names.size(); ++i)
  {
    const auto joint = f.model.getJoint(f.joint_names[i]);
    if (!joint->mimic)
      continue;
    for (unsigned int j = 0; j < f.joint_names.size(); ++j)
      if (f.joint_names[j] == joint->mimic->joint_name)
        q(i) = joint->mimic->multiplier * q(j) + joint->mimic->offset;
  }

  const KDL::Frame target = f.fk(q);
  // NOT a zero seed. The four main_boom_ext* joints are parallel prismatic joints, so their Jacobian
  // columns are identical; from an all-equal seed a pseudo-inverse step moves them by equal amounts
  // and the mimic violation stays invisible. An asymmetric seed is what exposes it.
  KDL::JntArray seed = f.randomConfig(rng), sol;
  ASSERT_GE(ik.CartToJnt(seed, target, sol), 0) << "no solution for a reachable crane pose";
  EXPECT_LT(positionError(target, f.fk(sol)), kPosTol) << "the 9 free joints do reach the target";
  expectWithinLimits(f, sol);

  // RED until ticket 04: the solver chooses all 9 joints independently, so the coupling is broken.
  for (unsigned int i = 0; i < f.joint_names.size(); ++i)
  {
    const auto joint = f.model.getJoint(f.joint_names[i]);
    if (!joint->mimic)
      continue;
    for (unsigned int j = 0; j < f.joint_names.size(); ++j)
      if (f.joint_names[j] == joint->mimic->joint_name)
        EXPECT_NEAR(sol(i), joint->mimic->multiplier * sol(j) + joint->mimic->offset, 1e-6)
            << f.joint_names[i] << " must follow " << f.joint_names[j];
  }
}

