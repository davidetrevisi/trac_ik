// The self-motion witness: one target, many seeds, genuinely different configurations that all
// reach it. This is the property ticket 07's "walk the candidate list against the validity
// callback" leans on and neither existing fixture has (the crane's spare DOF is a coupling, and
// arm6's square Jacobian gives isolated solutions only).
TEST(TracIkLib, Arm7HasANullSpaceOfSolutions)
{
  Fixture f("arm7.urdf", "base_link", "tool_link");
  TRAC_IK::TRAC_IK ik(f.chain, f.lb, f.ub, 0.05, kEps, TRAC_IK::Speed);

  std::mt19937 rng(9);
  const KDL::Frame target = f.fk(f.randomConfig(rng));

  std::vector<KDL::JntArray> found;
  for (int n = 0; n < 20; ++n)
  {
    KDL::JntArray seed = f.randomConfig(rng), sol;
    if (ik.CartToJnt(seed, target, sol) < 0)
      continue;
    ASSERT_LT(positionError(target, f.fk(sol)), kPosTol);
    ASSERT_LT(rotationError(target, f.fk(sol)), kRotTol);
    found.push_back(sol);
  }
  ASSERT_GE(found.size(), 5u) << "the redundant arm should reach one pose from most seeds";

  double widest = 0.0;
  for (size_t a = 0; a < found.size(); ++a)
    for (size_t b = a + 1; b < found.size(); ++b)
    {
      double d = 0.0;
      for (unsigned int i = 0; i < found[a].rows(); ++i)
        d = std::max(d, std::fabs(found[a](i) - found[b](i)));
      widest = std::max(widest, d);
    }
  EXPECT_GT(widest, 0.1) << "distinct solutions for one pose; widest joint spread " << widest;
}
